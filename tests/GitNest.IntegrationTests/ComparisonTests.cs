using SourceGit.Models;
using SourceGit.Commands;

internal static partial class Program
{
    private static async Task RunComparisonTestsAsync(string git, string root)
    {
        var repo = Path.Combine(root, "累计差异 & #");
        async Task<string> Run(params string[] args) => (await GitAsync(git, ["-C", repo, .. args])).Trim();
        await GitAsync(git, "init", "-b", "main", repo);
        await Run("config", "user.name", "Comparison tests");
        await Run("config", "user.email", "tests@example.invalid");
        var query = new QueryTaskComparison(repo, Path.Combine(repo, ".git"));
        Check((await query.ReadAsync("refs/heads/main", TaskComparisonMode.MergeBase)).Error == "TaskCompare.Unborn", "An unborn task has an explicit comparison state");
        File.WriteAllText(Path.Combine(repo, "改名之前.txt"), "stable\n");
        File.WriteAllBytes(Path.Combine(repo, "binary.dat"), [0, 1, 2, 3]);
        await Run("add", ".");
        await Run("commit", "-m", "base");
        var basis = await Run("rev-parse", "HEAD");
        await Run("checkout", "-b", "task/review");
        await Run("mv", "改名之前.txt", "改名之后 & #.txt");
        File.WriteAllText(Path.Combine(repo, "AI 成果.txt"), "one\ntwo\n");
        File.WriteAllBytes(Path.Combine(repo, "binary.dat"), [0, 4, 5, 6, 7]);
        await Run("add", ".");
        await Run("commit", "-m", "AI 第一批");
        File.AppendAllText(Path.Combine(repo, "AI 成果.txt"), "three\n");
        await Run("add", ".");
        await Run("commit", "-m", "AI 第二批");
        var taskHead = await Run("rev-parse", "HEAD");
        await Run("remote", "add", "publish", repo);
        await Run("update-ref", "refs/remotes/publish/task", taskHead);
        await Run("config", "branch.task/review.remote", "publish");
        await Run("config", "branch.task/review.merge", "refs/heads/task");
        await Run("checkout", "main");
        File.WriteAllText(Path.Combine(repo, "target-only.txt"), "target update\n");
        await Run("add", ".");
        await Run("commit", "-m", "target update");
        var targetHead = await Run("rev-parse", "HEAD");
        await Run("checkout", "task/review");
        var indexHash = Hash(Path.Combine(repo, ".git", "index"));
        var configHash = Hash(Path.Combine(repo, ".git", "config"));
        var snapshot = await query.ReadAsync("refs/heads/main", TaskComparisonMode.MergeBase);
        Check(snapshot.IsReadable && !snapshot.IsStale && snapshot.SourceHead == taskHead && snapshot.TargetHead == targetHead && snapshot.BaseHead == basis, "Comparison pins both tips and their unique merge base");
        Check(snapshot.Changes.Count == 3 && snapshot.Changes.All(c => c.Path != "target-only.txt"), "A clean task retains accumulated committed changes without target-only updates");
        Check(snapshot.Changes.Any(c => c.Path == "改名之后 & #.txt" && c.OriginalPath == "改名之前.txt" && c.Index == ChangeState.Renamed), "Rename parsing preserves Unicode and special-character paths");
        Check(snapshot.AddedLines == 3 && snapshot.DeletedLines == 0 && snapshot.BinaryFiles == 1, "Text statistics exclude binary line counts and retain the binary file count");
        Check(snapshot.CommitCount == 2 && snapshot.Commits.Count == 2 && snapshot.Commits[0].Subject == "AI 第二批", "Task-only commits span multiple AI commits in newest-first order");
        Check(snapshot.TargetRef == "refs/heads/main" && snapshot.WorkingCopy.Upstream == "publish/task", "The explicit comparison target is independent of the push upstream");
        var tips = await query.ReadAsync("refs/heads/main", TaskComparisonMode.TwoTips);
        Check(tips.BaseHead == targetHead && tips.Changes.Any(c => c.Path == "target-only.txt" && c.Index == ChangeState.Deleted), "Two-tip mode uses the target tip and shows target-only differences");
        File.AppendAllText(Path.Combine(repo, "AI 成果.txt"), "uncommitted\n");
        File.WriteAllText(Path.Combine(repo, "untracked.txt"), "new\n");
        var dirty = await query.ReadAsync("refs/heads/main", TaskComparisonMode.MergeBase);
        Check(dirty.AddedLines == snapshot.AddedLines && dirty.Changes.Count == snapshot.Changes.Count && dirty.WorkingCopy.ChangedFiles == 2, "Uncommitted work is counted separately from the immutable committed diff");
        Check(await query.IsCurrentAsync(snapshot), "Working-copy edits leave the committed comparison current");
        Check(Hash(Path.Combine(repo, ".git", "config")) == configHash && Hash(Path.Combine(repo, ".git", "index")) == indexHash, "Comparison reads preserve config and index bytes");
        var targets = await query.ReadTargetsAsync();
        Check(targets.Contains("refs/heads/main") && targets.Contains("refs/remotes/publish/task"), "Target choices retain full local and remote ref names");
        Check((await query.ReadAsync("--output=bad", TaskComparisonMode.TwoTips)).Error == "TaskCompare.TargetMissing", "Option-like input cannot become a Git argument");
        await Run("update-ref", "refs/heads/main", basis);
        Check(!await query.IsCurrentAsync(snapshot), "External target updates invalidate the fixed snapshot");
        await Run("update-ref", "refs/heads/main", targetHead);
        await Run("checkout", "-b", "same-tip");
        Check(!await query.IsCurrentAsync(snapshot), "A branch switch at the same hash invalidates the source identity");
        await Run("checkout", "task/review");
        await Run("add", ".");
        await Run("commit", "-m", "external commit");
        Check(!await query.IsCurrentAsync(snapshot), "An external task commit invalidates the previous snapshot");
        await Run("checkout", "--detach");
        var detached = await query.ReadAsync("refs/heads/main", TaskComparisonMode.MergeBase);
        Check(detached.IsReadable && detached.SourceRef == "HEAD", "Detached HEAD supports an explicit committed comparison");
        var tree = await Run("rev-parse", "HEAD^{tree}");
        var unrelated = await Run("commit-tree", tree, "-m", "unrelated root");
        await Run("update-ref", "refs/heads/unrelated", unrelated);
        Check((await query.ReadAsync("refs/heads/unrelated", TaskComparisonMode.MergeBase)).Error == "TaskCompare.NoMergeBase", "Unrelated histories do not invent a merge base");
        Check((await query.ReadAsync("refs/heads/unrelated", TaskComparisonMode.TwoTips)).IsReadable, "Unrelated tips can still be compared explicitly");
        var left = await Run("commit-tree", tree, "-p", basis, "-m", "left");
        var right = await Run("commit-tree", tree, "-p", basis, "-m", "right");
        var firstMerge = await Run("commit-tree", tree, "-p", left, "-p", right, "-m", "first merge");
        var secondMerge = await Run("commit-tree", tree, "-p", right, "-p", left, "-m", "second merge");
        await Run("update-ref", "refs/heads/criss-cross", firstMerge);
        await Run("checkout", "--detach", secondMerge);
        Check((await query.ReadAsync("refs/heads/criss-cross", TaskComparisonMode.MergeBase)).Error == "TaskCompare.MultipleMergeBases", "Criss-cross histories report multiple merge bases without selecting one");
        await Run("update-ref", "-d", "refs/heads/main");
        Check((await query.ReadAsync("refs/heads/main", TaskComparisonMode.TwoTips)).Error == "TaskCompare.TargetMissing", "Deleted comparison targets produce an explicit error");
        var wrongIdentity = new QueryTaskComparison(repo, Path.Combine(root, "another-common-dir"));
        Check((await wrongIdentity.ReadAsync("refs/heads/task/review", TaskComparisonMode.TwoTips)).Error == "Worktree.Status.IdentityChanged", "Comparisons reject a replaced repository identity");
    }
}
