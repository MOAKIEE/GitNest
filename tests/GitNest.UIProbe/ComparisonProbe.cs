using Avalonia.Controls;
using Avalonia.VisualTree;
using SourceGit;
using SourceGit.Models;
using VM = SourceGit.ViewModels;
using Views = SourceGit.Views;
using OS = SourceGit.Native.OS;

internal static partial class Program
{
    static partial void RunComparison()
    {
        var repoPath = Path.Combine(_root, "比较 主仓库");
        Git(_root, "init", "-b", "main", repoPath);
        Git(repoPath, "config", "user.name", "Probe");
        Git(repoPath, "config", "user.email", "probe@example.invalid");
        File.WriteAllText(Path.Combine(repoPath, "base.txt"), "base\n");
        Git(repoPath, "add", ".");
        Git(repoPath, "commit", "-m", "base");
        var basis = Git(repoPath, "rev-parse", "HEAD");
        var taskPath = Path.Combine(_root, "AI 累计成果 & #3");
        Git(repoPath, "worktree", "add", "-b", "task/review", taskPath);
        File.WriteAllText(Path.Combine(taskPath, "AI 成果.txt"), "first\nsecond\n");
        Git(taskPath, "add", ".");
        Git(taskPath, "commit", "-m", "AI 第一批成果");
        File.AppendAllText(Path.Combine(taskPath, "AI 成果.txt"), "third\n");
        File.WriteAllBytes(Path.Combine(taskPath, "binary.dat"), [0, 1, 2, 3]);
        Git(taskPath, "add", ".");
        Git(taskPath, "commit", "-m", "AI 第二批成果");
        var taskHead = Git(taskPath, "rev-parse", "HEAD");
        File.WriteAllText(Path.Combine(repoPath, "target-only.txt"), "target\n");
        Git(repoPath, "add", ".");
        Git(repoPath, "commit", "-m", "目标独有更新");
        var targetHead = Git(repoPath, "rev-parse", "HEAD");
        Git(repoPath, "update-ref", "refs/remotes/origin/main", targetHead);
        App.SetTheme("Light", "");
        _launcher = new VM.Launcher(repoPath);
        typeof(App).GetField("_launcher", System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.NonPublic)!.SetValue(Avalonia.Application.Current, _launcher);
        var repo = (VM.Repository)_launcher.ActivePage.Data;
        var view = new Views.Repository { DataContext = repo };
        _window = new Window { Content = view, Width = 1280, Height = 900, ShowInTaskbar = false, Title = "GitNest 累计差异探针" };
        _window.Show();
        Await(() => repo.Worktrees.Count == 2 && repo.Worktrees.All(t => t.Status?.IsReadable == true));
        var navigation = view.GetVisualDescendants().OfType<ListBox>().Single(list => list.Items.Count == 4 && list.Items[3] is ListBoxItem);
        navigation.SelectedIndex = 3;
        Await(() => repo.TaskComparison is { IsLoading: false });
        Check(repo.IsTaskComparisonVisible && WorktreeTaskStore.PathsEqual(repo.TaskComparison.FullPath, repoPath), "The navigation entry reviews the current worktree");
        repo.ShowTaskComparison(repo.Worktrees.Single(t => WorktreeTaskStore.PathsEqual(t.FullPath, taskPath)));
        var comparison = repo.TaskComparison;
        Await(() => !comparison.IsLoading && comparison.Targets.Count >= 3);
        Check(comparison.SelectedTarget is null or "" && comparison.Snapshot == null, "The task page requires an explicit comparison target");
        Check(comparison.WorkingCopyDescription == VM.Worktree.DescribeChanges(new WorktreeStatus { IsReadable = true }), "Uncommitted counts are available before choosing a target");
        Screenshot(_window, "comparison-choose-target");
        var comparisonView = view.GetVisualDescendants().OfType<Views.TaskComparison>().Single();
        comparisonView.FindControl<ComboBox>("TargetBox")!.SelectedItem = "refs/heads/main";
        Await(() => !comparison.IsLoading && comparison.Snapshot?.IsReadable == true);
        Await(() => comparison.DiffContext?.Content != null);
        Check(comparison.Snapshot.BaseHead == basis && comparison.Snapshot.Changes.Count == 2 && comparison.Snapshot.CommitCount == 2, "The page shows all committed task work from the merge base");
        Check(comparison.DiffContext.IsTextDiff, "Selecting a file loads the existing text diff viewer");
        Check(new WorktreeTaskStore(Path.Combine(OS.BasicDirectories.ConfigDir, "worktree-tasks.json")).Get(Path.Combine(repoPath, ".git"), taskPath).ComparisonTarget == "refs/heads/main", "The selected target persists for this worktree");
        Check(Git(repoPath, "rev-parse", "HEAD") == targetHead && Git(taskPath, "rev-parse", "HEAD") == taskHead, "Reviewing another worktree does not switch either branch");
        Screenshot(_window, "comparison-merge-base-light");
        var binary = comparison.Changes.Single(c => c.Path == "binary.dat");
        comparison.ChangeSelection = new VM.ChangeSelection(new[] { binary });
        Await(() => comparison.DiffContext?.Content is BinaryDiff);
        Check(!comparison.DiffContext.IsTextDiff && comparison.Snapshot.BinaryFiles == 1, "Binary selection uses the existing binary viewer and separate count");
        Screenshot(_window, "comparison-binary");
        comparisonView.FindControl<ComboBox>("ModeBox")!.SelectedIndex = 1;
        Await(() => !comparison.IsLoading && comparison.Snapshot?.Mode == TaskComparisonMode.TwoTips);
        Check(comparison.Changes.Any(c => c.Path == "target-only.txt" && c.Index == ChangeState.Deleted), "Changing comparison mode exposes target-only differences");
        App.SetTheme("Dark", "");
        _window.Width = 1060;
        _window.Height = 700;
        Screenshot(_window, "comparison-two-tips-dark-narrow");

        comparisonView.FindControl<ComboBox>("ModeBox")!.SelectedIndex = 0;
        Await(() => !comparison.IsLoading && comparison.Snapshot?.Mode == TaskComparisonMode.MergeBase);
        File.AppendAllText(Path.Combine(taskPath, "AI 成果.txt"), "uncommitted\n");
        Git(taskPath, "add", ".");
        File.AppendAllText(Path.Combine(taskPath, "AI 成果.txt"), "remaining\n");
        var validation = comparison.ValidateSnapshotAsync();
        Await(() => validation.IsCompleted);
        // A timer validation may already be running when the explicit request returns.
        Await(() => comparison.WorkingCopyDescription.Contains('1'));
        Check(!comparison.IsStale && comparison.Snapshot.AddedLines == 3 && comparison.WorkingCopyDescription.Contains('1'), "Uncommitted changes update separately without changing committed statistics");
        Git(repoPath, "update-ref", "refs/heads/main", basis);
        Await(() => comparison.IsStale);
        Check(comparison.Snapshot.IsStale && comparison.Snapshot.TargetHead == targetHead, "Background validation marks the old snapshot stale without replacing its hashes");
        var staleNotice = comparisonView.FindControl<Border>("StaleNotice")!;
        Check(staleNotice.IsEffectivelyVisible && ((TextBlock)staleNotice.Child!).Text == App.Text("TaskCompare.Stale"), "The visible stale notice explains that refresh is required");
        Screenshot(_window, "comparison-stale");
        var refresh = comparisonView.GetVisualDescendants().OfType<Button>().Single(b => b.Content?.ToString() == App.Text("TaskCompare.Refresh"));
        refresh.Command!.Execute(refresh.CommandParameter);
        Await(() => !comparison.IsLoading && !comparison.IsStale && comparison.Snapshot?.TargetHead == basis);
        Check(true, "The bound refresh command creates a current snapshot");
        repo.ShowTaskComparison(repo.Worktrees.Single(t => WorktreeTaskStore.PathsEqual(t.FullPath, taskPath)));
        comparison = repo.TaskComparison;
        Await(() => !comparison.IsLoading && comparison.Snapshot?.IsReadable == true);
        Check(comparison.SelectedTarget == "refs/heads/main", "Reopening the task restores the saved target");
        comparison.SelectedTarget = "refs/remotes/origin/main";
        Await(() => !comparison.IsLoading && comparison.Snapshot?.TargetRef == "refs/remotes/origin/main");
        Check(comparison.TargetCacheDescription == App.Text("TaskCompare.CachedTarget"), "A remote target is labeled as a local tracking cache");
        Screenshot(_window, "comparison-remote-cache");
        comparison.SelectedTarget = "refs/heads/main";
        comparison.SelectedTarget = "refs/remotes/origin/main";
        comparison.SelectedTarget = "refs/heads/main";
        Await(() => !comparison.IsLoading && comparison.Snapshot?.TargetRef == "refs/heads/main");
        Check(true, "A later target selection wins over an earlier in-flight read");
        Git(repoPath, "update-ref", "-d", "refs/heads/main");
        var readMissing = comparison.RefreshAsync();
        Await(() => readMissing.IsCompleted);
        Check(comparison.ErrorText == App.Text("TaskCompare.TargetMissing") && comparison.Changes.Count == 0 && comparison.DiffContext == null, "A deleted target clears old content and displays the real error");
        Screenshot(_window, "comparison-missing-target");
        Git(repoPath, "update-ref", "refs/heads/main", targetHead);
        comparison.SelectedTarget = "refs/heads/main";
        var read = comparison.RefreshAsync();
        Await(() => read.IsCompleted);
        comparison.ShowUncommittedChanges();
        Await(() => _launcher.ActivePage.Data is VM.Repository opened && WorktreeTaskStore.PathsEqual(opened.FullPath, taskPath) && opened.SelectedViewIndex == 1);
        Check(true, "The separate changes action opens the reviewed worktree's working copy");
        var pending = comparison.RefreshAsync();
        comparison.Dispose();
        Await(() => pending.IsCompleted);
        Check(comparison.Snapshot == null, "Disposed pages discard pending query results");
        CloseFixture();
    }
}
